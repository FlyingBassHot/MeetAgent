#!/usr/bin/env python3
"""Generate firmware/terminal/components/espui/phosphor/glyph_atlas.c.

Source font: JetBrains Mono Bold (JetBrainsMonoNerdFont-Bold.ttf), SIL OFL 1.1.
Cell: 18x27, 1bpp, threshold 45%, then one-pixel 8-neighbour dilation.
Only the ASCII subset used by the static/animated core is emitted.
"""
from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

CHARS = " .,:-=+*#%@/\\|<>^v;[]{}?_!o01"
CELL_W = 18
CELL_H = 27
ROW_BYTES = 3
THRESHOLD = "45%"
FONT = "/usr/share/fonts/TTF/JetBrainsMonoNerdFont-Bold.ttf"


def render_glyph(ch: str) -> list[list[int]]:
    cmd = [
        "convert", "-size", f"{CELL_W}x{CELL_H}", "xc:white",
        "-font", FONT, "-pointsize", "25", "-fill", "black",
        "-gravity", "center", "-annotate", "+0+0", ch,
        "-threshold", THRESHOLD, "pbm:-",
    ]
    data = subprocess.check_output(cmd, stderr=subprocess.DEVNULL)
    pos = 0
    for _ in range(2):
        pos = data.index(b"\n", pos) + 1
    stride = (CELL_W + 7) // 8
    raw = data[pos:pos + stride * CELL_H]
    return [list(raw[y * stride:(y + 1) * stride]) for y in range(CELL_H)]


def get_bit(rows: list[list[int]], x: int, y: int) -> bool:
    if x < 0 or x >= CELL_W or y < 0 or y >= CELL_H:
        return False
    return bool(rows[y][x // 8] & (0x80 >> (x % 8)))


def set_bit(rows: list[list[int]], x: int, y: int) -> None:
    rows[y][x // 8] |= 0x80 >> (x % 8)


def dilate(rows: list[list[int]]) -> list[list[int]]:
    out = [[0] * ROW_BYTES for _ in range(CELL_H)]
    for y in range(CELL_H):
        for x in range(CELL_W):
            if not get_bit(rows, x, y):
                continue
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < CELL_W and 0 <= ny < CELL_H:
                        set_bit(out, nx, ny)
    return out


def format_glyph(ch: str, rows: list[list[int]]) -> str:
    lines = [f"    {{ /* {ch} */"]
    for row in rows:
        lines.append("        " + ", ".join(f"0x{b:02X}" for b in row) + ",")
    lines.append("    },")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path(
        "components/espui/phosphor/glyph_atlas.c"))
    args = parser.parse_args()
    if not Path(FONT).exists():
        raise SystemExit(f"font not found: {FONT}")
    rows = [dilate(render_glyph(ch)) for ch in CHARS]
    escaped = CHARS.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "/*",
        " * PHOSPHOR 18x27 1bpp ASCII glyph atlas (P3.1).",
        " * Generated by tools/phosphor_atlas/generate_glyph_atlas.py.",
        " * Font: JetBrains Mono Bold, SIL Open Font License 1.1.",
        " * Threshold 45%, 1px 8-neighbour dilation; 18x27 cell, 3 bytes/row.",
        " */",
        '#include "glyph_atlas.h"',
        "",
        "#include <stddef.h>",
        "#include <string.h>",
        "",
        f'static const char s_glyph_chars[] = "{escaped}";',
        "static const uint8_t s_glyph_bitmap[][GLYPH_ATLAS_H * GLYPH_ATLAS_ROW_BYTES] = {",
    ]
    lines.extend(format_glyph(ch, r) for ch, r in zip(CHARS, rows))
    lines += [
        "};",
        "",
        "static const uint8_t s_blank[GLYPH_ATLAS_H * GLYPH_ATLAS_ROW_BYTES] = {0};",
        "",
        "uint8_t glyph_atlas_count(void)",
        "{",
        "    return (uint8_t)(sizeof(s_glyph_bitmap) / sizeof(s_glyph_bitmap[0]));",
        "}",
        "",
        "uint8_t glyph_atlas_index(char c)",
        "{",
        "    if (c == ' ') {",
        "        return 0;",
        "    }",
        "    for (uint8_t i = 0; i < glyph_atlas_count(); ++i) {",
        "        if (s_glyph_chars[i] == c) {",
        "            return i;",
        "        }",
        "    }",
        "    return 0;",
        "}",
        "",
        "bool glyph_atlas_contains(char c)",
        "{",
        "    if (c == ' ') {",
        "        return true;",
        "    }",
        "    for (uint8_t i = 1; i < glyph_atlas_count(); ++i) {",
        "        if (s_glyph_chars[i] == c) {",
        "            return true;",
        "        }",
        "    }",
        "    return false;",
        "}",
        "",
        "char glyph_atlas_char_at(uint8_t index)",
        "{",
        "    return index < glyph_atlas_count() ? s_glyph_chars[index] : ' ';",
        "}",
        "",
        "const uint8_t *glyph_atlas_bitmap(uint8_t index)",
        "{",
        "    return index < glyph_atlas_count() ? s_glyph_bitmap[index] : s_blank;",
        "}",
        "",
        "bool glyph_atlas_pixel(uint8_t index, uint8_t x, uint8_t y)",
        "{",
        "    if (index >= glyph_atlas_count() || x >= GLYPH_ATLAS_W ||",
        "        y >= GLYPH_ATLAS_H) {",
        "        return false;",
        "    }",
        "    const uint8_t *row = &s_glyph_bitmap[index][y * GLYPH_ATLAS_ROW_BYTES];",
        "    return (row[x / 8] & (0x80u >> (x % 8))) != 0;",
        "}",
        "",
    ]
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out} ({len(CHARS)} glyphs, {len(CHARS)*CELL_H*ROW_BYTES} bytes)")


if __name__ == "__main__":
    main()
